/**
 * What: Normalises OData metadata (V2 and V4 EDMX, parsed with SAP's @sap-ux/edmx-parser and
 *     annotation-converter) into one small service model: entity sets with keys, properties,
 *     navigations, capabilities, draft and ETag flags, and operations (actions/functions).
 * Why: The API diff and the test generator need the same, version-independent view of a service;
 *     draft plumbing is separated out so it neither shows up as API changes nor as test targets.
 * If missing or unlinked: odata-diff and odata-testgen cannot read service metadata.
 */
import { parse } from '@sap-ux/edmx-parser';
import { convert } from '@sap-ux/annotation-converter';

/**
 * @typedef {object} Property
 * @property {string} name
 * @property {string} type          EDM type, e.g. Edm.String
 * @property {boolean} nullable
 * @property {boolean} key
 * @property {boolean} computed     Server-computed (not settable by clients)
 * @property {boolean} immutable    Settable on create only
 * @property {boolean} mandatory    Must be provided on create
 * @property {boolean} foreignKey   Part of a navigation's referential constraint
 * @property {number} [maxLength]
 * @property {number} [precision]
 * @property {number | string} [scale]
 *
 * @typedef {{ name: string, target: string, isCollection: boolean }} Navigation
 * @typedef {{ readable: boolean, insertable: boolean, updatable: boolean, deletable: boolean }} Capabilities
 *
 * @typedef {object} EntitySet
 * @property {string} name
 * @property {string} entityType
 * @property {string[]} keys
 * @property {Property[]} properties
 * @property {Navigation[]} navigations
 * @property {Capabilities} capabilities
 * @property {boolean} draft
 * @property {boolean} etag  ETag support (V4 Core.OptimisticConcurrency present; CAP may emit it empty)
 *
 * @typedef {object} Operation
 * @property {string} name
 * @property {'action' | 'function'} kind
 * @property {boolean} bound
 * @property {string} [entitySet]    Entity set the operation is bound to
 * @property {Array<{ name: string, type: string, nullable: boolean }>} parameters
 * @property {string} [returnType]
 *
 * @typedef {{ name: string, entitySets: EntitySet[], operations: Operation[] }} Service
 * @typedef {{ formatVersion: 1, odataVersion: '2.0' | '4.0', services: Service[] }} ServiceModel
 */

/** Draft plumbing generated by CAP/RAP; not part of the business API. */
const DRAFT_PROPERTIES = new Set(['IsActiveEntity', 'HasActiveEntity', 'HasDraftEntity', 'DraftMessages', 'DraftAdministrativeData_DraftUUID']);
const DRAFT_NAVIGATIONS = new Set(['DraftAdministrativeData', 'SiblingEntity']);
const DRAFT_ACTIONS = new Set(['draftPrepare', 'draftActivate', 'draftEdit']);
const DRAFT_SETS = new Set(['DraftAdministrativeData']);

/** @param {string} a @param {string} b */
const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * @param {string} xml  EDMX document (OData V2 or V4)
 * @returns {ServiceModel}
 */
export function fromEdmx(xml) {
  let converted;
  try {
    converted = /** @type {any} */ (convert(parse(xml)));
  } catch (err) {
    throw new MetadataError(`Not a valid EDMX document: ${/** @type {Error} */ (err).message}`);
  }
  const odataVersion = converted.version === '4.0' ? '4.0' : '2.0';
  const serviceName = converted.namespace;

  /** @type {EntitySet[]} */
  const entitySets = converted.entitySets
    .filter((/** @type {any} */ es) => !DRAFT_SETS.has(es.name))
    .map((/** @type {any} */ es) => toEntitySet(es))
    .sort((/** @type {EntitySet} */ a, /** @type {EntitySet} */ b) => byName(a.name, b.name));

  const setOfType = new Map(converted.entitySets.map((/** @type {any} */ es) => [es.entityType.fullyQualifiedName, es.name]));
  /** @type {Operation[]} */
  const operations = converted.actions
    .filter((/** @type {any} */ a) => !DRAFT_ACTIONS.has(a.name))
    .map((/** @type {any} */ a) => {
      const params = /** @type {any[]} */ (a.parameters ?? []);
      const binding = a.isBound ? params[0] : undefined;
      return /** @type {Operation} */ ({
        name: a.name,
        kind: a.isFunction ? 'function' : 'action',
        bound: Boolean(a.isBound),
        ...(binding ? { entitySet: setOfType.get(String(binding.type).replace(/^Collection\(|\)$/g, '')) ?? String(binding.type) } : {}),
        parameters: params.slice(binding ? 1 : 0).map((p) => ({ name: p.name, type: String(p.type), nullable: p.nullable !== false })),
        ...(a.returnType ? { returnType: String(a.returnType) } : {}),
      });
    })
    .sort((/** @type {Operation} */ a, /** @type {Operation} */ b) => byName(`${a.entitySet ?? ''}/${a.name}`, `${b.entitySet ?? ''}/${b.name}`));

  return { formatVersion: 1, odataVersion, services: [{ name: serviceName, entitySets, operations }] };
}

/**
 * @param {any} es  converted entity set
 * @returns {EntitySet}
 */
function toEntitySet(es) {
  const type = es.entityType;
  const keys = type.keys.map((/** @type {any} */ k) => k.name).filter((/** @type {string} */ k) => !DRAFT_PROPERTIES.has(k));
  /** @type {Set<string>} */
  const foreignKeys = new Set();
  for (const nav of type.navigationProperties ?? []) {
    for (const rc of nav.referentialConstraint ?? []) foreignKeys.add(rc.sourceProperty);
  }
  const caps = es.annotations?.Capabilities ?? {};
  /** @type {Property[]} */
  const properties = type.entityProperties
    .filter((/** @type {any} */ p) => !DRAFT_PROPERTIES.has(p.name))
    .map((/** @type {any} */ p) => {
      const core = p.annotations?.Core ?? {};
      const fieldControl = String(p.annotations?.Common?.FieldControl ?? '');
      const key = keys.includes(p.name);
      const computed = Boolean(core.Computed) || Boolean(core.ComputedDefaultValue && key);
      return /** @type {Property} */ ({
        name: p.name,
        type: String(p.type),
        nullable: p.nullable !== false,
        key,
        computed,
        immutable: Boolean(core.Immutable),
        mandatory: !computed && (fieldControl.endsWith('Mandatory') || (p.nullable === false && !key)),
        foreignKey: foreignKeys.has(p.name),
        ...(p.maxLength !== undefined ? { maxLength: Number(p.maxLength) } : {}),
        ...(p.precision !== undefined ? { precision: Number(p.precision) } : {}),
        ...(p.scale !== undefined ? { scale: p.scale } : {}),
      });
    })
    .sort((/** @type {Property} */ a, /** @type {Property} */ b) => byName(a.name, b.name));
  return {
    name: es.name,
    entityType: type.name,
    keys,
    properties,
    navigations: (type.navigationProperties ?? [])
      .filter((/** @type {any} */ n) => !DRAFT_NAVIGATIONS.has(n.name))
      .map((/** @type {any} */ n) => ({ name: n.name, target: n.targetTypeName?.split('.').pop() ?? '', isCollection: Boolean(n.isCollection) }))
      .sort((/** @type {Navigation} */ a, /** @type {Navigation} */ b) => byName(a.name, b.name)),
    capabilities: {
      readable: caps.ReadRestrictions?.Readable !== false,
      insertable: caps.InsertRestrictions?.Insertable !== false,
      updatable: caps.UpdateRestrictions?.Updatable !== false,
      deletable: caps.DeleteRestrictions?.Deletable !== false,
    },
    draft: Boolean(es.annotations?.Common?.DraftRoot || es.annotations?.Common?.DraftNode),
    etag: es.annotations?.Core?.OptimisticConcurrency !== undefined,
  };
}

export class MetadataError extends Error {
  /** @param {string} message */
  constructor(message) {
    super(message);
    this.name = 'MetadataError';
  }
}

/**
 * Validates a stored snapshot (JSON written by --snapshot).
 * @param {any} value
 * @returns {ServiceModel}
 */
export function parseSnapshot(value) {
  if (value?.formatVersion !== 1 || !Array.isArray(value.services) || !['2.0', '4.0'].includes(value.odataVersion)) {
    throw new MetadataError('Not a service-model snapshot (formatVersion 1 with services[])');
  }
  return value;
}

/**
 * Merges several single-service models (e.g. one per CAP service) into one.
 * @param {ServiceModel[]} models
 * @returns {ServiceModel}
 */
export function mergeModels(models) {
  const services = models.flatMap((m) => m.services).sort((a, b) => byName(a.name, b.name));
  return { formatVersion: 1, odataVersion: models[0]?.odataVersion ?? '4.0', services };
}
