/**
 * What: Emits a Postman collection (v2.1) from the test plan: one folder per entity set and one
 *     for unbound operations, ordered requests (create -> read -> update -> operations -> delete)
 *     with status assertions, key capture in collection variables, and credentials as variables.
 * Why: Deployed services (RAP, S/4HANA, CAP on BTP) are tested over HTTP with Newman in pipelines
 *     and interactively in Postman, using the same plan as the CAP node:test output.
 * If missing or unlinked: odata-testgen cannot produce tests for deployed or non-CAP services.
 */

/**
 * @typedef {import('./plan.js').ServicePlan} ServicePlan
 * @typedef {import('./plan.js').EntityPlan} EntityPlan
 * @typedef {import('./plan.js').OperationPlan} OperationPlan
 * @typedef {import('./access.js').User} User
 */

const SCHEMA = 'https://schema.getpostman.com/json/collection/v2.1.0/collection.json';

/**
 * @param {ServicePlan[]} plans
 * @param {{ name: string, command: string }} options
 */
export function emitPostman(plans, { name, command }) {
  /** @type {Map<string, User>} */
  const users = new Map();
  for (const plan of plans) {
    for (const e of plan.entities) for (const u of [e.reader, e.writer, e.deniedReader, e.deniedWriter]) if (u) users.set(u.name, u);
    for (const p of [...plan.unbound, ...plan.entities.flatMap((e) => e.boundOperations)]) for (const u of [p.allowedUser, p.deniedUser]) if (u) users.set(u.name, u);
  }
  return {
    info: {
      name: `${name} - generated API tests`,
      schema: SCHEMA,
      description: `GENERATED by odata-testgen. Regenerate with \`${command} --emit postman\`; do not edit by hand.\nRun: npx newman run <file> --env-var baseUrl=https://host --reporters cli,junit`,
    },
    variable: [
      { key: 'baseUrl', value: 'http://localhost:4004' },
      ...[...users.values()].flatMap((u) => [
        { key: `user_${u.name}`, value: u.name },
        { key: `password_${u.name}`, value: u.password },
      ]),
    ],
    item: plans.flatMap((plan) => [
      ...plan.entities.map((e) => ({ name: `${plan.service}.${e.set.name}`, item: entityRequests(e) })),
      ...(plan.unbound.length ? [{ name: `${plan.service} operations`, item: plan.unbound.flatMap((p) => operationRequests(p, plan.basePath, undefined)) }] : []),
    ]),
  };
}

/**
 * @param {string} name
 * @param {string} method
 * @param {string} url
 * @param {User | undefined} user
 * @param {{ body?: unknown, status: number | number[], script?: string[], headers?: Array<{ key: string, value: string }> }} spec
 */
function request(name, method, url, user, { body, status, script = [], headers = [] }) {
  const expected = Array.isArray(status) ? status : [status];
  const check =
    expected[0] === -1
      ? `pm.test('reachable (no 401/403/404/5xx)', () => pm.expect(pm.response.code < 500 && ![401, 403, 404, 405].includes(pm.response.code)).to.be.true);`
      : `pm.test('status ${expected.join(' or ')}', () => pm.expect(${JSON.stringify(expected)}).to.include(pm.response.code));`;
  return {
    name,
    event: [{ listen: 'test', script: { type: 'text/javascript', exec: [check, ...script] } }],
    request: {
      method,
      header: [...(body !== undefined ? [{ key: 'Content-Type', value: 'application/json' }] : []), ...headers],
      ...(body !== undefined ? { body: { mode: 'raw', raw: JSON.stringify(body, null, 2) } } : {}),
      // String form: Newman does not parse a URL object that only carries "raw".
      url: `{{baseUrl}}${url}`,
      auth: user
        ? { type: 'basic', basic: [{ key: 'username', value: `{{user_${user.name}}}`, type: 'string' }, { key: 'password', value: `{{password_${user.name}}}`, type: 'string' }] }
        : { type: 'noauth' },
    },
  };
}

/**
 * @param {EntityPlan} e
 */
function entityRequests(e) {
  const { set } = e;
  const base = `${e.basePath}/${set.name}`;
  const keyVar = `key_${set.name}`;
  const caps = set.capabilities;
  /** @type {any[]} */
  const items = [];
  const payload = { ...e.payload };
  for (const k of set.keys) {
    const p = set.properties.find((x) => x.name === k);
    if (p && !p.computed) payload[k] = p.type === 'Edm.Guid' ? '{{$guid}}' : p.type.startsWith('Edm.Int') ? '{{$timestamp}}' : 'K{{$timestamp}}';
  }
  // Key predicate built from the response inside Postman (single or composite keys, draft flag).
  // Plain string concatenation: these lines are code for Postman, not template literals for us.
  const capture = (/** @type {boolean | undefined} */ active) => {
    const keyDefs = JSON.stringify(set.keys.map((k) => ({ k, s: set.properties.find((p) => p.name === k)?.type === 'Edm.String' })));
    const named = set.keys.length > 1 || active !== undefined;
    return [
      'const d = pm.response.json();',
      'const keys = ' + keyDefs + ';',
      'const parts = keys.map((x) => ' + (named ? "x.k + '=' + " : '') + '(x.s ? "\'" + d[x.k] + "\'" : String(d[x.k])));',
      ...(active !== undefined ? ["parts.push('IsActiveEntity=" + active + "');"] : []),
      "pm.collectionVariables.set('" + keyVar + "', '(' + parts.join(',') + ')');",
      ...(set.etag ? [captureEtag] : []),
    ];
  };
  // Every write changes the ETag; CAP rejects writes without If-Match (428) on ETag entities.
  const etagVar = `etag_${set.name}`;
  const captureEtag = "pm.collectionVariables.set('" + etagVar + "', pm.response.json()['@odata.etag']);";
  const ifMatch = set.etag && !set.draft ? [{ key: 'If-Match', value: `{{${etagVar}}}` }] : [];

  if (e.anonymousDenied) items.push(request('anonymous read -> 401', 'GET', base, undefined, { status: 401 }));
  if (caps.readable && e.reader) items.push(request(`read collection as ${e.reader.name}`, 'GET', `${base}?$top=2&$count=true`, e.reader, { status: 200 }));
  if (caps.readable && e.deniedReader) items.push(request(`read as ${e.deniedReader.name} -> 403`, 'GET', base, e.deniedReader, { status: 403 }));
  if (caps.insertable && e.deniedWriter) items.push(request(`create as ${e.deniedWriter.name} -> 403`, 'POST', base, e.deniedWriter, { body: payload, status: 403 }));
  if (!(caps.insertable && e.writer)) return items;

  if (e.mandatory.length && !set.draft) {
    const incomplete = { ...payload };
    for (const m of e.mandatory) delete incomplete[m];
    items.push(request(`create without ${e.mandatory.join(', ')} -> 400`, 'POST', base, e.writer, { body: incomplete, status: 400 }));
  }
  if (e.typedProperty) items.push(request(`create with invalid ${e.typedProperty.name} -> 400`, 'POST', base, e.writer, { body: { ...payload, [e.typedProperty.name]: 'not-a-valid-value' }, status: 400 }));

  if (!caps.readable) {
    // The caller may create but not read: 204 without body, so no key for follow-up requests.
    items.push(request(`create as ${e.writer.name}`, 'POST', base, e.writer, { body: payload, status: [201, 204] }));
    return items;
  }
  items.push(request(`create as ${e.writer.name}`, 'POST', base, e.writer, { body: payload, status: 201, script: capture(set.draft ? false : undefined) }));
  if (set.draft) {
    items.push(request('activate draft', 'POST', `${base}{{${keyVar}}}/${e.service}.draftActivate`, e.writer, { body: {}, status: [200, 201], script: capture(true) }));
  }
  if (caps.readable && e.reader) items.push(request('read created entity', 'GET', `${base}{{${keyVar}}}`, e.reader, { status: 200 }));
  if (caps.updatable && e.stringProperty && !set.draft) {
    items.push(
      request(`update ${e.stringProperty.name}`, 'PATCH', `${base}{{${keyVar}}}`, e.writer, {
        body: { [e.stringProperty.name]: 'U' },
        status: 200,
        headers: ifMatch,
        script: set.etag ? [captureEtag] : [],
      }),
    );
    if (set.etag) {
      items.push(request('update with stale ETag -> 412', 'PATCH', `${base}{{${keyVar}}}`, e.writer, { body: { [e.stringProperty.name]: 'U' }, status: 412, headers: [{ key: 'If-Match', value: 'W/"stale"' }] }));
    }
  }
  for (const p of e.boundOperations) items.push(...operationRequests(p, base, `{{${keyVar}}}/${e.service}.`));
  if (caps.deletable) items.push(request('delete created entity', 'DELETE', `${base}{{${keyVar}}}`, e.writer, { status: 204, headers: ifMatch }));
  return items;
}

/**
 * @param {OperationPlan} p
 * @param {string} base
 * @param {string | undefined} boundPrefix  key + service qualifier for bound operations
 */
function operationRequests(p, base, boundPrefix) {
  const { op } = p;
  const args = `(${Object.entries(p.params).map(([k, v]) => `${k}=${typeof v === 'string' ? `'${v}'` : v}`).join(',')})`;
  const url = `${base}${boundPrefix ? boundPrefix : '/'}${op.name}${op.kind === 'function' ? args : ''}`;
  const method = op.kind === 'function' ? 'GET' : 'POST';
  const body = op.kind === 'function' ? undefined : p.params;
  /** @type {any[]} */
  const items = [];
  if (p.allowedUser) items.push(request(`${op.kind} ${op.name} as ${p.allowedUser.name} (smoke)`, method, url, p.allowedUser, { body, status: -1 }));
  if (p.deniedUser) items.push(request(`${op.kind} ${op.name} as ${p.deniedUser.name} -> 403`, method, url, p.deniedUser, { body, status: 403 }));
  if (p.anonymousDenied && !boundPrefix) items.push(request(`${op.kind} ${op.name} anonymous -> 401`, method, url, undefined, { body, status: 401 }));
  return items;
}
